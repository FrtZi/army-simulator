// The readable page of the defects register, docs/defects.md: an index, then one section per defect.
import { COMMIT, STATED_PROOF, STATUSES, TAGS, TYPES, isoDate } from "./defects-format.mjs";

const statusLabel = (defect) => `${STATUSES[defect.statut]} ${defect.statut}`;

function card(defect) {
  const meta = [`\`${isoDate(defect.date)}\``, defect.type, defect.gravite, statusLabel(defect)];
  meta.push(`tags: ${defect.etiquettes.map((tag) => `\`${tag}\``).join(", ")}`);
  if (defect.reconstitue) meta.push("*reconstructed after the fact*");
  const proofs = defect.preuve.map((proof) => (STATED_PROOF.test(proof) ? proof : `\`${proof}\``)).join(", ");
  const links = (defect.liens ?? []).map((link) => (COMMIT.test(link) ? `\`${link}\`` : link)).join(", ");
  const fields = [
    ["Finding", defect.constat],
    ["Cause", defect.cause],
    ["Solution", defect.solution],
    ["Result", defect.resultat],
    ["Lesson", defect.lecon],
    ["Proof", proofs || "to cover"],
    ["Links", links],
  ];
  const lines = [
    `<a id="${defect.id.toLowerCase()}"></a>`,
    `### ${defect.id} · ${defect.titre}`,
    "",
    meta.join(" · "),
    "",
  ];
  return lines.concat(
    fields.filter(([, text]) => text).map(([label, text]) => `- **${label}:** ${text}`),
    "",
  );
}

/** The whole page, from the register's entries (already checked). */
export function page(defects) {
  const counts = Object.keys(STATUSES).map(
    (status) => `${defects.filter((d) => d.statut === status).length} ${status}`,
  );
  const lines = [
    "<!-- Generated by scripts/defects.mjs from docs/defects.toml: never edit by hand. -->",
    "# Defects register",
    "",
    "[← Overview](../ARCHITECTURE.md) · Source: [defects.toml](defects.toml) · Catalogue: [features.md](features.md)",
    "",
    "What broke, why, how it was settled, and what keeps it from coming back. One entry per real defect",
    "detected (code, configuration, content, tool, environment, third party or the way we work), each",
    `with its regression test, check or rule. **${defects.length} defects**: ${counts.join(", ")}.`,
    "",
    `Types: ${TYPES.join(", ")}. Tags: ${TAGS.join(", ")}.`,
    "",
    "## Index",
    "",
    "| ID | Date | Defect | Type | Severity | Status |",
    "|---|---|---|---|---|---|",
    ...defects.map((d) => {
      const cells = [`[${d.id}](#${d.id.toLowerCase()})`, isoDate(d.date), d.titre, d.type, d.gravite, statusLabel(d)];
      return `| ${cells.join(" | ")} |`;
    }),
    "",
    "## Entries",
    "",
  ];
  return lines.concat(defects.flatMap(card)).join("\n");
}
